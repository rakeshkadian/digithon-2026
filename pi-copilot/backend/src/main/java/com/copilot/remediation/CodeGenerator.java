package com.copilot.remediation;

import com.copilot.model.ClassInfo;
import com.copilot.model.EntityInfo;
import com.copilot.model.FieldInfo;
import com.copilot.model.RepoSnapshot;
import com.copilot.persistence.FindingEntity;
import com.github.javaparser.StaticJavaParser;
import com.github.javaparser.ast.CompilationUnit;
import com.github.javaparser.ast.body.BodyDeclaration;
import com.github.javaparser.ast.body.ClassOrInterfaceDeclaration;
import com.github.javaparser.ast.body.MethodDeclaration;
import com.github.javaparser.printer.lexicalpreservation.LexicalPreservingPrinter;
import lombok.Data;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.*;
import java.util.stream.Collectors;

/**
 * Turns approved findings into concrete file changes inside the cloned target repo.
 * Golden rule: never change an existing column or method; only add.
 */
@Slf4j
@Service
public class CodeGenerator {

    @Data
    public static class GeneratedFile {
        private String path;
        private String action;     // ADDED | MODIFIED
        private String content;    // new content
        private String original;   // for MODIFIED
    }

    @Data
    public static class Result {
        private String sql;
        private List<GeneratedFile> files = new ArrayList<>();
        private String prBody;
    }

    public Result generate(Path repoDir, RepoSnapshot snap, List<FindingEntity> approved) throws IOException {
        Result result = new Result();
        String basePkg = snap.getBasePackage();
        String persistencePkg = detectPersistencePackage(repoDir, snap);
        String srcRoot = "src/main/java/" + basePkg.replace('.', '/');

        Map<String, List<FindingEntity>> byTable = approved.stream()
                .collect(Collectors.groupingBy(FindingEntity::getTableName, LinkedHashMap::new, Collectors.toList()));

        // 1. shared support classes (added once)
        add(result, srcRoot + "/security/pi/PiCrypto.java", Templates.piCrypto(basePkg));
        add(result, srcRoot + "/security/pi/EncryptedStringConverter.java", Templates.converter(basePkg, persistencePkg));
        add(result, srcRoot + "/security/pi/PiFlags.java", Templates.flags(basePkg));
        add(result, srcRoot + "/security/pi/PiFlagController.java", Templates.flagController(basePkg));

        // 2. per table: SQL + entity + repository + lookup service
        StringBuilder sql = new StringBuilder("-- Generated by PI Security Co-Pilot. Additive only; existing columns untouched.\n");
        int version = nextFlywayVersion(repoDir);

        for (var e : byTable.entrySet()) {
            String table = e.getKey();
            List<FindingEntity> cols = e.getValue();
            EntityInfo entity = snap.getEntities().stream().filter(x -> x.getTableName().equals(table)).findFirst()
                    .orElseThrow(() -> new IllegalStateException("entity not found for table " + table));

            sql.append("\nALTER TABLE ").append(table).append("\n");
            List<String> alters = new ArrayList<>();
            for (FindingEntity f : cols) {
                alters.add("  ADD COLUMN IF NOT EXISTS " + f.getColumnName() + "_enc BYTEA");
                if (needsBlindIndex(f)) alters.add("  ADD COLUMN IF NOT EXISTS " + f.getColumnName() + "_bidx VARCHAR(64)");
            }
            alters.add("  ADD COLUMN IF NOT EXISTS pi_key_ver INT");
            sql.append(String.join(",\n", alters)).append(";\n");
            for (FindingEntity f : cols) {
                if (needsBlindIndex(f))
                    sql.append("CREATE INDEX IF NOT EXISTS idx_").append(table).append('_').append(f.getColumnName())
                       .append("_bidx ON ").append(table).append(" (").append(f.getColumnName()).append("_bidx);\n");
            }

            modifyEntity(repoDir, result, entity, cols, basePkg, persistencePkg);
            ClassInfo repo = findRepository(snap, entity);
            if (repo != null) modifyRepository(repoDir, result, repo, entity, cols);
            if (repo != null && cols.stream().anyMatch(this::needsBlindIndex)) {
                addLookupService(repoDir, result, srcRoot, basePkg, entity, repo, cols);
            }
        }
        result.setSql(sql.toString());
        add(result, "src/main/resources/db/migration/V" + version + "__pi_encrypt.sql", sql.toString());

        // 3. config
        appendConfig(repoDir, result);

        result.setPrBody(prBody(approved));
        return result;
    }

    // ------------------------------------------------------------------ entity

    private void modifyEntity(Path repoDir, Result result, EntityInfo entity, List<FindingEntity> cols,
                              String basePkg, String persistencePkg) throws IOException {
        Path file = repoDir.resolve(entity.getFilePath());
        String original = Files.readString(file);
        CompilationUnit cu = StaticJavaParser.parse(original);
        LexicalPreservingPrinter.setup(cu);
        ClassOrInterfaceDeclaration clazz = cu.getClassByName(entity.getClassName())
                .orElseThrow(() -> new IllegalStateException("class not found " + entity.getClassName()));

        String conv = basePkg + ".security.pi.EncryptedStringConverter";
        String crypto = basePkg + ".security.pi.PiCrypto";
        StringBuilder sync = new StringBuilder();

        for (FindingEntity f : cols) {
            String enc = f.getJavaField() + "Enc";
            String bidx = f.getJavaField() + "Bidx";
            String getter = "get" + cap(f.getJavaField()) + "()";
            if (!hasField(clazz, enc)) {
                clazz.addMember(member(
                        "@" + persistencePkg + ".Convert(converter = " + conv + ".class)\n" +
                        "@" + persistencePkg + ".Column(name = \"" + f.getColumnName() + "_enc\")\n" +
                        "private String " + enc + ";"));
            }
            sync.append("    this.").append(enc).append(" = ").append(getter).append(";\n");
            if (needsBlindIndex(f)) {
                if (!hasField(clazz, bidx)) {
                    clazz.addMember(member(
                            "@" + persistencePkg + ".Column(name = \"" + f.getColumnName() + "_bidx\", length = 64)\n" +
                            "private String " + bidx + ";"));
                }
                sync.append("    this.").append(bidx).append(" = ").append(crypto).append(".blindIndex(").append(getter).append(");\n");
            }
        }
        if (!hasField(clazz, "piKeyVer")) {
            clazz.addMember(member("@" + persistencePkg + ".Column(name = \"pi_key_ver\")\nprivate Integer piKeyVer;"));
        }
        sync.append("    this.piKeyVer = ").append(crypto).append(".KEY_VERSION;\n");

        if (clazz.getMethodsByName("syncPiColumns").isEmpty()) {
            clazz.addMember(member(
                    "/** Generated by PI Security Co-Pilot: dual-write plain -> encrypted on every save. */\n" +
                    "@" + persistencePkg + ".PrePersist\n" +
                    "@" + persistencePkg + ".PreUpdate\n" +
                    "void syncPiColumns() {\n" + sync + "}"));
        }
        // getters so services can read the encrypted twin if they want to
        for (FindingEntity f : cols) {
            String enc = f.getJavaField() + "Enc";
            if (clazz.getMethodsByName("get" + cap(enc)).isEmpty() && !hasLombokGetter(clazz)) {
                clazz.addMember(member("public String get" + cap(enc) + "() { return " + enc + "; }"));
            }
        }

        modified(result, entity.getFilePath(), original, LexicalPreservingPrinter.print(cu));
    }

    // ------------------------------------------------------------------ repository

    private void modifyRepository(Path repoDir, Result result, ClassInfo repo, EntityInfo entity,
                                  List<FindingEntity> cols) throws IOException {
        Path file = repoDir.resolve(repo.getFilePath());
        String original = Files.readString(file);
        CompilationUnit cu = StaticJavaParser.parse(original);
        LexicalPreservingPrinter.setup(cu);
        ClassOrInterfaceDeclaration iface = cu.getInterfaceByName(repo.getClassName())
                .orElseThrow(() -> new IllegalStateException("repository not found " + repo.getClassName()));

        boolean changed = false;
        for (FindingEntity f : cols) {
            if (!needsBlindIndex(f)) continue;
            String name = "findBy" + cap(f.getJavaField()) + "Bidx";
            if (iface.getMethodsByName(name).isEmpty()) {
                iface.addMember(member("java.util.Optional<" + entity.getClassName() + "> " + name
                        + "(String " + f.getJavaField() + "Bidx);"));
                changed = true;
            }
        }
        if (changed) modified(result, repo.getFilePath(), original, LexicalPreservingPrinter.print(cu));
    }

    // ------------------------------------------------------------------ lookup service

    private void addLookupService(Path repoDir, Result result, String srcRoot, String basePkg, EntityInfo entity,
                                  ClassInfo repo, List<FindingEntity> cols) throws IOException {
        CompilationUnit repoCu = StaticJavaParser.parse(repoDir.resolve(repo.getFilePath()));
        String repoPkg = repoCu.getPackageDeclaration().map(p -> p.getNameAsString()).orElse(basePkg);
        CompilationUnit entCu = StaticJavaParser.parse(repoDir.resolve(entity.getFilePath()));
        String entPkg = entCu.getPackageDeclaration().map(p -> p.getNameAsString()).orElse(basePkg);

        StringBuilder methods = new StringBuilder();
        for (FindingEntity f : cols) {
            if (!needsBlindIndex(f)) continue;
            String cap = cap(f.getJavaField());
            String legacy = "Optional.empty() /* no legacy findBy" + cap + " in repository */";
            Optional<MethodDeclaration> legacyMethod = repoCu.findAll(MethodDeclaration.class).stream()
                    .filter(m -> m.getNameAsString().equals("findBy" + cap)).findFirst();
            if (legacyMethod.isPresent()) {
                boolean returnsOptional = legacyMethod.get().getType().asString().startsWith("Optional");
                legacy = returnsOptional ? "repo.findBy" + cap + "(value)" : "Optional.ofNullable(repo.findBy" + cap + "(value))";
            }
            methods.append(Templates.lookupMethod(entity.getClassName(), cap, legacy));
        }
        add(result, srcRoot + "/security/pi/" + entity.getClassName() + "PiLookupService.java",
                Templates.lookupService(basePkg, entity.getClassName(), entPkg + "." + entity.getClassName(),
                        repoPkg + "." + repo.getClassName(), methods.toString()));
    }

    // ------------------------------------------------------------------ config + helpers

    private void appendConfig(Path repoDir, Result result) throws IOException {
        Path yml = repoDir.resolve("src/main/resources/application.yml");
        Path props = repoDir.resolve("src/main/resources/application.properties");
        if (Files.exists(yml)) {
            String orig = Files.readString(yml);
            if (!orig.contains("pi:")) {
                modified(result, "src/main/resources/application.yml", orig,
                        orig + "\n# PI Security Co-Pilot\npi:\n  encryption: ${PI_ENCRYPTION:false}\n");
            }
        } else {
            String orig = Files.exists(props) ? Files.readString(props) : "";
            if (!orig.contains("pi.encryption")) {
                GeneratedFile g = new GeneratedFile();
                g.setPath("src/main/resources/application.properties");
                g.setAction(Files.exists(props) ? "MODIFIED" : "ADDED");
                g.setOriginal(orig);
                g.setContent(orig + "\n# PI Security Co-Pilot\npi.encryption=${PI_ENCRYPTION:false}\n");
                result.getFiles().add(g);
            }
        }
    }

    private String detectPersistencePackage(Path repoDir, RepoSnapshot snap) throws IOException {
        if (snap.getEntities().isEmpty()) return "jakarta.persistence";
        String src = Files.readString(repoDir.resolve(snap.getEntities().get(0).getFilePath()));
        return src.contains("javax.persistence") ? "javax.persistence" : "jakarta.persistence";
    }

    private int nextFlywayVersion(Path repoDir) throws IOException {
        Path dir = repoDir.resolve("src/main/resources/db/migration");
        if (!Files.isDirectory(dir)) return 2;
        try (var s = Files.list(dir)) {
            return s.map(p -> p.getFileName().toString())
                    .filter(n -> n.matches("V\\d+__.*"))
                    .map(n -> Integer.parseInt(n.substring(1, n.indexOf("__"))))
                    .max(Integer::compare).orElse(1) + 1;
        }
    }

    private ClassInfo findRepository(RepoSnapshot snap, EntityInfo entity) {
        return snap.getRepositories().stream()
                .filter(r -> entity.getClassName().equals(r.getManagedEntity()))
                .findFirst().orElse(null);
    }

    boolean needsBlindIndex(FindingEntity f) {
        return "ENCRYPT_WITH_BLIND_INDEX".equals(f.getRecommendation());
    }

    private static boolean hasField(ClassOrInterfaceDeclaration c, String name) {
        return c.getFieldByName(name).isPresent();
    }

    private static boolean hasLombokGetter(ClassOrInterfaceDeclaration c) {
        return c.isAnnotationPresent("Data") || c.isAnnotationPresent("Getter");
    }

    private static BodyDeclaration<?> member(String src) {
        return StaticJavaParser.parseBodyDeclaration(src);
    }

    static String cap(String s) {
        return Character.toUpperCase(s.charAt(0)) + s.substring(1);
    }

    private static void add(Result r, String path, String content) {
        GeneratedFile g = new GeneratedFile();
        g.setPath(path);
        g.setAction("ADDED");
        g.setContent(content);
        r.getFiles().add(g);
    }

    private static void modified(Result r, String path, String original, String content) {
        GeneratedFile g = new GeneratedFile();
        g.setPath(path);
        g.setAction("MODIFIED");
        g.setOriginal(original);
        g.setContent(content);
        r.getFiles().add(g);
    }

    private static String prBody(List<FindingEntity> approved) {
        StringBuilder sb = new StringBuilder("## PI Security Co-Pilot – encrypt approved personal data columns\n\n");
        sb.append("| Table | Column | PI type | Confidence | Change |\n|---|---|---|---|---|\n");
        for (FindingEntity f : approved) {
            sb.append("| ").append(f.getTableName()).append(" | ").append(f.getColumnName()).append(" | ")
              .append(f.getPiType()).append(" | ").append(f.getConfidence()).append("% | ")
              .append(f.getRecommendation()).append(" |\n");
        }
        sb.append("\n**Additive only.** Existing columns and methods are untouched. ")
          .append("New `*_enc` columns are written on every save (dual-write). ")
          .append("Set `PI_MASTER_KEY` in the environment. Flip `pi.encryption` or call `POST /pi/flag` to switch; ")
          .append("flip back for instant rollback.\n");
        return sb.toString();
    }

    /** Write all generated/modified files into the clone. */
    public void writeToRepo(Path repoDir, Result result) throws IOException {
        for (GeneratedFile g : result.getFiles()) {
            Path p = repoDir.resolve(g.getPath());
            Files.createDirectories(p.getParent());
            Files.writeString(p, g.getContent());
        }
    }
}
